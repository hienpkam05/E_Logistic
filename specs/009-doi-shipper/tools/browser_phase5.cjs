const { chromium, expect } = require('../../../frontend/node_modules/.cache/spec009-browser/node_modules/playwright/test')
const fs = require('node:fs')
const path = require('node:path')
const data = JSON.parse(fs.readFileSync(0, 'utf8'))

async function main() {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  const problems = []
  const contexts = []
  const base = 'http://127.0.0.1:5180'
  async function login(user) {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    contexts.push(context)
    const page = await context.newPage()
    page.on('pageerror', error => problems.push(error.message))
    page.on('console', msg => { if (/\[Vue.*warn/i.test(msg.text())) problems.push(msg.text()) })
    await page.goto(base + '/login')
    await page.getByLabel('Tên đăng nhập', { exact: false }).fill(user)
    await page.getByLabel('Mật khẩu', { exact: false }).fill(data.password)
    await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
    await page.waitForURL(url => !url.pathname.includes('login'))
    return page
  }
  async function detail(page, id) {
    await page.goto(base + '/staff/shipments/' + id)
    await expect(page.locator('#staff-shipment-title')).toHaveText(/HTT/)
    await expect(page.getByRole('heading', { name: 'Điều phối', exact: true })).toBeVisible()
  }
  async function snapshot(page, name, width) {
    await page.setViewportSize({ width, height: 1000 })
    await page.screenshot({ path: path.join(data.output, name + '-' + width + '.png'), fullPage: true, animations: 'disabled' })
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
    if (overflow) throw new Error('Horizontal overflow: ' + name + '/' + width)
  }
  async function chooseReplacement(page, targetName = data.newName, excludedName = data.oldName) {
    await page.locator('.page__actions').getByRole('button', { name: 'Đổi Shipper', exact: true }).click()
    const dialog = page.locator('dialog[open]')
    await expect(dialog.getByText(targetName, { exact: true })).toBeVisible()
    await expect(dialog.locator('.picker__item').filter({ hasText: excludedName })).toHaveCount(0)
    await dialog.locator('.picker__item').filter({ hasText: targetName }).getByRole('radio').check()
    await dialog.getByLabel('Lý do đổi Shipper', { exact: false }).fill('Nghỉ đột xuất, chuyển nhiệm vụ')
    await dialog.getByRole('button', { name: 'Xác nhận đổi Shipper', exact: true }).click()
    await expect(dialog).not.toBeVisible()
  }
  async function shipment(page, id) {
    return page.evaluate(async id => {
      const response = await fetch('/api/v1/shipments/' + id + '/')
      if (!response.ok) throw new Error('Shipment GET failed: ' + response.status)
      return response.json()
    }, id)
  }
  try {
    const staff = await login(data.admin)
    const old = await login(data.old)
    const next = await login(data.next)
    await detail(staff, data.pickup)
    await chooseReplacement(staff)
    const pickup = await shipment(staff, data.pickup)
    const pickupNew = pickup.tasks.find(t => t.status === 'ACTIVE')
    if (pickupNew.shipper.id !== data.nextId) throw new Error('Pickup not reassigned')
    await old.goto(base + '/shipper/tasks/' + data.pickupTask)
    await expect(old.locator('#task-title')).toHaveText(/HTT/)
    await expect(old.getByText('Nhiệm vụ đã chuyển cho Shipper khác.', { exact: false })).toBeVisible()
    await expect(old.locator('.task-actions')).toHaveCount(0)
    await next.goto(base + '/shipper/tasks/' + pickupNew.id)
    await next.getByRole('button', { name: 'Đã lấy hàng', exact: true }).click()
    await next.locator('dialog[open]').getByRole('button', { name: 'Tôi đã nhận đủ hàng', exact: true }).click()
    await expect(next.getByText('Đã ghi nhận lấy hàng.', { exact: false })).toBeVisible()
    console.log('PASS pickup swap: old read-only; new shipper completed pickup through UI')

    await detail(staff, data.delivery)
    await chooseReplacement(staff)
    await expect(staff.getByText('Chờ bàn giao đổi Shipper — dự kiến:', { exact: false })).toBeVisible()
    await snapshot(staff, 'staff-pending', 1440)
    await snapshot(staff, 'staff-pending', 390)
    await old.goto(base + '/shipper/tasks/' + data.deliveryTask)
    await expect(old.getByRole('heading', { name: 'Đưa hàng về để bàn giao', exact: true })).toBeVisible()
    await expect(old.locator('.cod-card')).toHaveCount(0)
    await snapshot(old, 'shipper-handover', 390)
    await snapshot(old, 'shipper-handover', 1440)
    await old.getByRole('button', { name: 'Đã đưa hàng về điểm tập kết', exact: true }).click()
    await old.locator('dialog[open]').getByRole('button', { name: 'Tôi đã giao hàng cho điểm tập kết', exact: true }).click()
    await expect(old.getByText('Đã báo đưa hàng về để đổi Shipper.', { exact: false })).toBeVisible()
    await expect(old.locator('.task-actions')).toHaveCount(0)
    await detail(staff, data.delivery)
    await staff.locator('.page__actions').getByRole('button', { name: 'Xác nhận nhận hàng bàn giao', exact: true }).click()
    const receive = staff.locator('dialog[open]')
    await expect(receive.getByRole('button', { name: 'Xác nhận bàn giao', exact: true })).toBeDisabled()
    await snapshot(staff, 'staff-confirm', 390)
    await snapshot(staff, 'staff-confirm', 1440)
    await receive.getByRole('checkbox').check()
    await receive.getByRole('button', { name: 'Xác nhận bàn giao', exact: true }).click()
    await expect(receive).not.toBeVisible()
    const delivery = await shipment(staff, data.delivery)
    const newTask = delivery.tasks.find(t => t.status === 'ACTIVE')
    if (newTask.attempt_no !== 2 || delivery.delivery_attempts !== 1) throw new Error('Attempt counter changed')
    await old.reload()
    await expect(old.getByText('Nhiệm vụ đã chuyển cho Shipper khác.', { exact: false })).toBeVisible()
    await next.goto(base + '/shipper/tasks/' + newTask.id)
    await expect(next.getByRole('button', { name: 'Giao thành công', exact: true })).toBeVisible()
    await expect(next.locator('.task-type')).toContainText('lần 2/3')
    console.log('PASS delivery swap: old reported handover; staff confirmed; new task kept attempt 2')

    await staff.goto(base + '/staff/accounts/' + data.nextId)
    await staff.getByRole('button', { name: 'Khóa tài khoản', exact: true }).click()
    const lock = staff.locator('dialog[open]')
    await expect(lock.getByText(delivery.tracking_code, { exact: true })).toBeVisible()
    await snapshot(staff, 'lock-open-tasks', 1440)
    await snapshot(staff, 'lock-open-tasks', 390)
    await lock.getByRole('button', { name: 'Hủy', exact: true }).click()

    // Nghiệm thu: lần 1 thất bại đã có trong fixture; bấm thật thất bại lần 2, đổi người ở lần 3.
    async function failDelivery(page) {
      await page.getByRole('button', { name: 'Giao thất bại', exact: true }).click()
      const dialog = page.locator('dialog[open]')
      await dialog.locator('select').selectOption('RECEIVER_UNREACHABLE')
      await dialog.getByRole('button', { name: 'Ghi nhận thất bại', exact: true }).click()
      await expect(page.getByText('Đã ghi nhận giao thất bại.', { exact: false })).toBeVisible()
    }
    await failDelivery(next)
    await detail(staff, data.delivery)
    await staff.locator('.page__actions').getByRole('button', { name: 'Giao lại', exact: true }).click()
    let dialog = staff.locator('dialog[open]')
    await dialog.locator('textarea').fill('Hẹn giao lần 3')
    await dialog.getByRole('button', { name: 'Giao lại', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await staff.locator('.page__actions').getByRole('button', { name: 'Phân công giao hàng', exact: true }).click()
    dialog = staff.locator('dialog[open]')
    await dialog.getByRole('checkbox').check()
    await dialog.getByRole('button', { name: 'Phân công giao', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await chooseReplacement(staff, data.oldName, data.newName)
    let third = await shipment(staff, data.delivery)
    const pendingThird = third.tasks.find(t => t.status === 'PENDING_SWAP_HANDOVER')
    await next.goto(base + '/shipper/tasks/' + pendingThird.id)
    await next.getByRole('button', { name: 'Đã đưa hàng về điểm tập kết', exact: true }).click()
    await next.locator('dialog[open]').getByRole('button', { name: 'Tôi đã giao hàng cho điểm tập kết', exact: true }).click()
    await expect(next.locator('dialog[open]')).toHaveCount(0)
    await detail(staff, data.delivery)
    await staff.locator('.page__actions').getByRole('button', { name: 'Xác nhận nhận hàng bàn giao', exact: true }).click()
    dialog = staff.locator('dialog[open]')
    await dialog.getByRole('checkbox').check()
    await dialog.getByRole('button', { name: 'Xác nhận bàn giao', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    third = await shipment(staff, data.delivery)
    const thirdTask = third.tasks.find(t => t.status === 'ACTIVE')
    if (thirdTask.attempt_no !== 3 || third.delivery_attempts !== 2) throw new Error('Swap reset third attempt')
    await old.goto(base + '/shipper/tasks/' + thirdTask.id)
    await failDelivery(old)
    await detail(staff, data.delivery)
    await expect(staff.locator('.page__actions').getByRole('button', { name: 'Giao lại', exact: true })).toHaveCount(0)
    if ((await shipment(staff, data.delivery)).delivery_attempts !== 3) throw new Error('Wrong final attempt count')
    await snapshot(staff, 'staff-three-attempts', 1440)
    await snapshot(staff, 'staff-three-attempts', 390)
    await staff.locator('.page__actions').getByRole('button', { name: 'Chuyển hoàn', exact: true }).click()
    dialog = staff.locator('dialog[open]')
    await dialog.locator('textarea').fill('Đã giao ba lần, chuyển hoàn')
    await dialog.getByRole('button', { name: 'Chuyển hoàn', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    if ((await shipment(staff, data.delivery)).status !== 'AWAITING_RETURN') throw new Error('Return not decided')
    console.log('PASS three attempts: swap on attempt 3; third failure cannot redeliver; staff decided return')
    if (problems.length) throw new Error(JSON.stringify(problems))
    console.log('PASS lock dialog / 10 screenshots / zero Vue warnings and page errors')
  } finally {
    await Promise.all(contexts.map(context => context.close()))
    await browser.close()
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
